#!/usr/bin/env python3
"""Benchmark real passive object-size inspection on a bounded, inert PDF.

Only generated bytes are measured. This cannot scan, clear, or authorize opening.
"""

import argparse
import json
import math
import statistics
import time

from pdf_embedded_object_sizes import inspect_pdf_embedded_object_sizes

IMAGE_OBJECTS = 256
ATTACHMENTS = 24
EXPECTED_STREAMS = 1 + IMAGE_OBJECTS + ATTACHMENTS
MIN_SAMPLES = 3
MAX_SAMPLES = 10
ERROR = "Embedded-object benchmark failed or was incomplete; no measurements recorded."


def fixture():
  """Create one valid PDF with referenced image XObjects and inert file streams."""
  objects = {}

  def stream(properties, payload):
    return (b"<< " + properties + b" /Length " + str(len(payload)).encode() +
            b" >>\nstream\n" + payload + b"\nendstream")

  images = range(5, 5 + IMAGE_OBJECTS)
  attachments = range(5 + IMAGE_OBJECTS, 5 + IMAGE_OBJECTS + ATTACHMENTS)
  specs = range(5 + IMAGE_OBJECTS + ATTACHMENTS,
                5 + IMAGE_OBJECTS + 2 * ATTACHMENTS)
  xobjects = b" ".join(
    f"/Im{index} {number} 0 R".encode()
    for index, number in enumerate(images)
  )
  commands = b"".join(f"q /Im{index} Do Q\n".encode()
                      for index in range(IMAGE_OBJECTS))
  names = b" ".join(
    f"(fixture-{index:03}.txt) {number} 0 R".encode()
    for index, number in enumerate(specs)
  )
  objects[1] = (b"<< /Type /Catalog /Pages 2 0 R /Names << /EmbeddedFiles "
                b"<< /Names [" + names + b"] >> >> >>")
  objects[2] = b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>"
  objects[3] = (b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
                b"/Resources << /XObject << " + xobjects +
                b" >> >> /Contents 4 0 R >>")
  objects[4] = stream(b"", commands)
  for number in images:
    objects[number] = stream(
      b"/Type /XObject /Subtype /Image /Width 1 /Height 1 "
      b"/ColorSpace /DeviceGray /BitsPerComponent 8", b"Z"
    )
  for index, (attached, spec) in enumerate(zip(attachments, specs)):
    objects[attached] = stream(b"/Type /EmbeddedFile",
                               f"Harmless test data {index:03}\n".encode())
    objects[spec] = (f"<< /Type /Filespec /F (fixture-{index:03}.txt) "
                     f"/EF << /F {attached} 0 R >> >>").encode()

  data = bytearray(b"%PDF-1.4\n%synthetic\n")
  offsets = [0]
  for number in range(1, len(objects) + 1):
    offsets.append(len(data))
    data.extend(f"{number} 0 obj\n".encode())
    data.extend(objects[number] + b"\nendobj\n")
  xref = len(data)
  data.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode())
  for offset in offsets[1:]:
    data.extend(f"{offset:010} 00000 n \n".encode())
  data.extend((f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\n"
               f"startxref\n{xref}\n%%EOF\n").encode())
  return bytes(data)


def benchmark(samples=5, *, inspector=inspect_pdf_embedded_object_sizes,
              clock=time.perf_counter_ns):
  """Time one discarded warmup and complete repeated real inspection calls."""
  if type(samples) is not int or not MIN_SAMPLES <= samples <= MAX_SAMPLES:
    raise ValueError("Choose three to ten benchmark samples.")
  pdf = fixture()
  durations = []
  for index in range(samples + 1):
    try:
      started = clock()
      result = inspector(pdf)
      elapsed = clock() - started
      if (result.stream_count != EXPECTED_STREAMS or
          result.embedded_stream_count != ATTACHMENTS or
          result.has_large_objects or result.permits_open is not False or
          type(elapsed) not in (float, int) or not math.isfinite(elapsed) or
          elapsed <= 0):
        raise RuntimeError(ERROR)
    except Exception:
      # Never expose a private path, underlying parser diagnostics, or partial data.
      raise RuntimeError(ERROR) from None
    if index:
      durations.append(elapsed)
  durations.sort()
  return {
    "schemaVersion": 1,
    "scope": "passiveEmbeddedObjectSizeInspectionOnly",
    "fixture": "syntheticImageXObjectsAndAttachments",
    "fixtureBytes": len(pdf),
    "imageXObjects": IMAGE_OBJECTS,
    "embeddedFiles": ATTACHMENTS,
    "inspectedStreams": EXPECTED_STREAMS,
    "sampleCount": samples,
    "discardedWarmupRuns": 1,
    "medianMilliseconds": round(statistics.median(durations) / 1_000_000, 3),
    "p90Milliseconds": round(durations[math.ceil(samples * .9) - 1] / 1_000_000, 3),
    "authorizesOpen": False,
  }


def main(argv=None):
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--samples", type=int, default=5)
  args = parser.parse_args(argv)
  try:
    report = benchmark(args.samples)
  except (ValueError, RuntimeError) as exc:
    parser.exit(1, str(exc) + "\n")
  print(json.dumps(report, sort_keys=True, allow_nan=False))
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
