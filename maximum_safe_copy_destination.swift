import AppKit
import Foundation
import UniformTypeIdentifiers

// Optional Maximum-only destination picker (opener-0545). This helper only
// asks where a verified copy could be saved. It never writes, scans or opens
// PDFs, changes preferences, or activates the unavailable Maximum profile.
enum MaximumSafeCopyDestination {
    static func configure(_ panel: NSSavePanel) {
        panel.title = "Save Sanitized PDF Copy"
        panel.message = "Choose a permanent destination for the newly generated PDF. The original is not changed."
        panel.prompt = "Choose Destination"
        panel.nameFieldStringValue = "sanitized-copy.pdf"
        panel.allowedContentTypes = [.pdf]
        panel.canCreateDirectories = true
        panel.isExtensionHidden = false
    }

    static func selectedURL(
        response: NSApplication.ModalResponse, url: URL?
    ) -> URL? {
        guard response == .OK,
              let url,
              url.isFileURL,
              url.path.hasPrefix("/"),
              url.pathExtension.lowercased() == "pdf" else { return nil }
        // A destination is only a choice, not authorization to overwrite an
        // original, bypass a fresh scan, or write any generated bytes.
        return url.standardizedFileURL
    }

    static func requestDestination(
        present: (NSSavePanel) -> (NSApplication.ModalResponse, URL?) = {
            panel in (panel.runModal(), panel.url)
        }
    ) -> URL? {
        let panel = NSSavePanel()
        configure(panel)
        let (response, url) = present(panel)
        return selectedURL(response: response, url: url)
    }
}

#if !MAXIMUM_DESTINATION_TESTING
@main
struct MaximumSafeCopyDestinationCommand {
    static func main() {
        // Never permit caller-supplied paths or noninteractive auto-selection.
        guard CommandLine.arguments.count == 1,
              let destination = MaximumSafeCopyDestination.requestDestination() else {
            exit(EXIT_FAILURE)
        }
        // NUL-delimited output handles arbitrary valid pathname characters.
        // No PDF data or source path is passed to this helper.
        var path = Data(destination.path.utf8)
        path.append(0)
        FileHandle.standardOutput.write(path)
    }
}
#endif
