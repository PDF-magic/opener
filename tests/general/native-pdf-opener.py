#!/usr/bin/env python3
"""Exercise native open events against a slow, harmless substitute scan process."""
from pathlib import Path
import subprocess
import tempfile

source = (Path(__file__).resolve().parents[2] / 'brave-pdf-opener.swift').read_text()
classes = source.split("@main\nstruct PDFMagicOpenerEntry {")[0]
classes += "\n" + (Path(__file__).resolve().parents[2] / "scan-progress-view.swift").read_text()
classes += "\n" + (Path(__file__).resolve().parents[2] / "PDFMagicOpenerApp" / "ScanProgressPreference.swift").read_text().replace("import Foundation\n", "")
with tempfile.TemporaryDirectory(prefix='studio-opener-test-') as directory:
    root = Path(directory)
    (root / "twilight-reading.png").write_bytes(
        (Path(__file__).resolve().parents[2] / "twilight-reading.png").read_bytes())
    gate = root / 'gate.py'
    calls = root / 'calls'
    document = root / 'document.pdf'
    document.touch()
    alias = root / 'selected alias.pdf'
    alias.symlink_to(document)
    # Simulate Finder opening a PDF on /Volumes, including spaces and Unicode.
    # The runner need not mount physical media: macOS passes both as file URLs.
    external = root / 'Volumes' / 'External SSD' / 'Quarterly report – 2026.PDF'
    external.parent.mkdir(parents=True)
    others = [external, root / 'document-1.pdf', root / '報告 #3 & 100% (final).pdf']
    for other in others:
        other.touch()
    assert 'startAccessingSecurityScopedResource()' in source
    assert 'stopAccessingSecurityScopedResource()' in source
    # Paths are generated by tempfile, with no shell interpolation of user input.
    gate.write_text(
        "import pathlib, sys, time\n"
        "with pathlib.Path(" + repr(str(calls)) + ").open('a', encoding='utf-8') as output:\n"
        "    output.write('start ' + sys.argv[1] + '\\n')\n"
        "time.sleep(1)\n"
        "with pathlib.Path(" + repr(str(calls)) + ").open('a', encoding='utf-8') as output:\n"
        "    output.write('end ' + sys.argv[1] + '\\n')\n"
    )
    # Test actual FIFO scheduling on the main queue, not OS-level process-start
    # timestamps: two worker subprocesses can be launched FIFO yet run out of order.
    dispatches = root / 'scan-dispatch-order'
    start_scan = '    private func startScan(_ path: String) {\n'
    assert classes.count(start_scan) == 1, 'Native scan dispatch hook changed'
    classes = classes.replace(
        start_scan,
        start_scan +
        f'        let dispatchLog = URL(fileURLWithPath: "{dispatches}")\n' +
        '        let previous = (try? String(contentsOf: dispatchLog, encoding: .utf8)) ?? ""\n' +
        '        try? (previous + path + "\\n").write(to: dispatchLog, atomically: true, encoding: .utf8)\n'
    )
    classes = classes.replace(
        'FileManager.default.homeDirectoryForCurrentUser\n'
        '            .appendingPathComponent("Library/Application Support/Studio/allow-and-open/scan-and-open.py")',
        f'URL(fileURLWithPath: "{gate}")')
    harness = classes + f'''
let app = NSApplication.shared
let delegate = PDFOpener()
app.delegate = delegate
app.setActivationPolicy(.accessory)
let document = URL(fileURLWithPath: "{document}")
let alias = URL(fileURLWithPath: "{alias}")
let extraOne = URL(fileURLWithPath: "{others[0]}")
let extraTwo = URL(fileURLWithPath: "{others[1]}")
let extraThree = URL(fileURLWithPath: "{others[2]}")
DispatchQueue.main.async {{
    delegate.application(app, open: [alias, alias, document])
    guard let panel = app.windows.compactMap({{ $0 as? NSPanel }}).first,
          !panel.hidesOnDeactivate, panel.isVisible else {{
        fatalError("The scan panel must stay visible while another app is active")
    }}
    guard panel.contentView?.subviews.compactMap({{ $0 as? NSTextField }})
            .contains(where: {{ $0.stringValue == "selected alias.pdf" }}) == true else {{
        fatalError("Progress must display the original requested alias filename")
    }}
    precondition((panel as? ScanProgressPanel)?.stageLabel.stringValue == ScanProgressStage.starting.label,
                 "Native scan must start in the pending-launch stage")
    delegate.application(app, open: [extraOne, extraTwo, extraThree])
    guard let progress = panel as? ScanProgressPanel,
          progress.filenameLabel.stringValue.contains("4 documents"),
          ["selected alias.pdf", "Quarterly report – 2026.PDF"].contains(where: {{
              progress.filenameLabel.stringValue.contains($0)
          }}) else {{
        fatalError("Concurrent scans must show an active filename and the document count")
    }}
    precondition(progress.queuedDocumentCountLabel.stringValue == "2 documents queued",
                 "Two active scans leave exactly two queued documents")
    precondition(progress.queuedDocumentCountLabel.accessibilityLabel() == "2 documents queued",
                 "VoiceOver must receive the actual queued document count")
}}
DispatchQueue.main.asyncAfter(deadline: .now() + 0.2) {{
    delegate.application(app, open: [document, alias])
    guard let progress = app.windows.compactMap({{ $0 as? ScanProgressPanel }}).first,
          progress.filenameLabel.stringValue.contains("4 documents"),
          ["selected alias.pdf", "Quarterly report – 2026.PDF"].contains(where: {{
              progress.filenameLabel.stringValue.contains($0)
          }}) else {{
        fatalError("Duplicate events must preserve active filename and pending count")
    }}
    precondition(progress.queuedDocumentCountLabel.stringValue == "2 documents queued",
                 "Duplicate opens must not increase the queue count")
}}
// Assert the stage advances only when the harmless native scan child launches.
func verifyLaunchedStage(_ attempts: Int = 0) {{
    guard let panel = app.windows.compactMap({{ $0 as? ScanProgressPanel }}).first else {{
        fatalError("Expected native progress panel")
    }}
    if panel.stageLabel.stringValue == ScanProgressStage.scanning.label {{
        return
    }}
    precondition(attempts < 30, "Native scan never reported its launched stage")
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {{
        verifyLaunchedStage(attempts + 1)
    }}
}}
DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {{
    verifyLaunchedStage()
}}
// Observe the queue draining on the main run loop rather than assuming the
// CI runner dispatches all four subprocesses within a bounded window.
var observedQueueDrained = false
func verifyWaitingQueueDrained(_ attempts: Int = 0) {{
    guard let progress = app.windows.compactMap({{ $0 as? ScanProgressPanel }}).first else {{
        fatalError("Expected native progress panel while scans are queued")
    }}
    if progress.queuedDocumentCountLabel.stringValue == "0 documents queued" {{
        observedQueueDrained = true
        return
    }}
    precondition(attempts < 150, "Newly dispatched files must leave the waiting count")
    DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) {{
        verifyWaitingQueueDrained(attempts + 1)
    }}
}}
DispatchQueue.main.asyncAfter(deadline: .now() + 0.4) {{
    verifyWaitingQueueDrained()
}}
// Capture an offscreen rendering of the drawing, without reading the desktop.
DispatchQueue.main.asyncAfter(deadline: .now() + 0.3) {{
    let view = TwilightReadingView(frame: NSRect(x: 0, y: 0, width: 300, height: 205))
    if let bitmap = view.bitmapImageRepForCachingDisplay(in: view.bounds) {{
        view.cacheDisplay(in: view.bounds, to: bitmap)
        try? bitmap.representation(using: .png, properties: [:])?.write(to: URL(fileURLWithPath: "/tmp/studio-twilight-reading.png"))
    }}
}}
app.run()
precondition(observedQueueDrained,
             "Native scans finished before the queued document count reached zero")
'''
    swift = root / 'test.swift'
    swift.write_text(harness)
    binary = root / 'opener'
    subprocess.run(['/usr/bin/xcrun', 'swiftc', str(swift), '-o', str(binary)], check=True)
    subprocess.run([str(binary)], check=True, timeout=35)
    events = [line.split(' ', 1) for line in calls.read_text().splitlines()]
    active = 0
    peak = 0
    started = []
    finished = []
    for event, path in events:
        if event == 'start':
            active += 1
            peak = max(peak, active)
            started.append(path)
        elif event == 'end':
            active -= 1
            finished.append(path)
        else:
            raise AssertionError(f'Unexpected event: {event}')
        assert 0 <= active <= 2, 'Native dispatch exceeded the two-scan limit'
    expected = [str(document)] + [str(path) for path in others]
    # The application dispatches in FIFO order on its main queue. Python process
    # startup is scheduled independently by macOS and may reorder the start lines.
    assert dispatches.read_text().splitlines() == expected, (
        'Native queued scans must dispatch in FIFO order'
    )
    assert set(started) == set(expected) and len(started) == len(expected), (
        'Every approved scan must actually start exactly once'
    )
    assert set(finished) == set(expected) and len(finished) == len(expected)
    assert peak == 2 and active == 0, 'Two distinct scans must overlap and all scans must finish'
    print('PASS: external-volume PDF paths, original aliases, duplicate suppression, and queued scans.')

    started = root / 'termination-started'
    ended = root / 'termination-eof'
    gate.write_text(
        "import pathlib, sys\n"
        "pathlib.Path(" + repr(str(started)) + ").write_text('started')\n"
        "sys.stdin.buffer.read()\n"
        "pathlib.Path(" + repr(str(ended)) + ").write_text('eof')\n"
    )
    termination_harness = classes + f'''
let app = NSApplication.shared
let delegate = PDFOpener()
app.delegate = delegate
app.setActivationPolicy(.accessory)
DispatchQueue.main.async {{
    delegate.application(app, open: [URL(fileURLWithPath: "{document}")])
}}
DispatchQueue.main.asyncAfter(deadline: .now() + 1.0) {{
    app.terminate(nil)
}}
app.run()
'''
    swift.write_text(termination_harness)
    subprocess.run(['/usr/bin/xcrun', 'swiftc', str(swift), '-o', str(binary)], check=True)
    subprocess.run([str(binary)], check=True, timeout=15)
    assert started.exists(), 'The scan child did not start before app termination'
    import time
    deadline = time.monotonic() + 5
    while not ended.exists() and time.monotonic() < deadline:
        time.sleep(0.05)
    assert ended.exists(), 'The scan child did not receive EOF when the app terminated'
    print('PASS: app termination closes the scan lifetime pipe.')


    # opener-0172: open the separate SwiftUI Settings application while the
    # native PDF-owner process has a scan in progress. The settings executable
    # is built earlier in the macOS CI job and does not own the scan lifetime.
    import os
    settings_binary = Path(os.environ.get("RUNNER_TEMP", "/nonexistent")) / (
        "PDFMagicOpenerDerived/Build/Products/Debug/"
        "PDFMagicOpener.app/Contents/MacOS/PDFMagicOpener"
    )
    if os.environ.get("CI"):
        assert settings_binary.is_file(), "Standalone Settings build is missing"
    if settings_binary.is_file():
        scan_started = root / "settings-scan-started"
        scan_finished = root / "settings-scan-finished"
        gate.write_text(
            "import pathlib, time\n"
            "pathlib.Path(" + repr(str(scan_started)) + ").write_text('started')\n"
            "time.sleep(3)\n"
            "pathlib.Path(" + repr(str(scan_finished)) + ").write_text('finished')\n"
        )
        live_harness = classes + f'''
let app = NSApplication.shared
let delegate = PDFOpener()
app.delegate = delegate
app.setActivationPolicy(.accessory)
DispatchQueue.main.async {{
    delegate.application(app, open: [URL(fileURLWithPath: "{document}")])
}}
app.run()
'''
        swift.write_text(live_harness)
        subprocess.run(
            ["/usr/bin/xcrun", "swiftc", str(swift), "-o", str(binary)], check=True
        )
        scan_owner = subprocess.Popen(
            [str(binary)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL
        )
        settings_owner = None
        try:
            deadline = time.monotonic() + 8
            while (not scan_started.exists() and scan_owner.poll() is None
                   and time.monotonic() < deadline):
                time.sleep(0.05)
            assert scan_started.exists(), "Native scanner did not start"
            # Do not invoke a Settings action on the scan owner. The separate
            # SwiftUI app can open its preferences without closing the
            # scanner's lifetime pipe or cancelling the pending request.
            settings_owner = subprocess.Popen(
                [str(settings_binary)],
                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
            )
            time.sleep(0.3)
            assert settings_owner.poll() is None, "Settings application exited"
            assert scan_owner.poll() is None, "Opening Settings stopped the scan"
            assert scan_owner.wait(timeout=15) == 0, "Native scan owner failed"
            assert scan_finished.exists(), "Scan was interrupted by Settings"
            assert settings_owner.poll() is None, (
                "Settings must remain usable after a scan finishes"
            )
            print("PASS: Settings opens while scanning and does not interrupt it.")
        finally:
            if scan_owner.poll() is None:
                scan_owner.terminate()
                try:
                    scan_owner.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    scan_owner.kill()
                    scan_owner.wait(timeout=5)
            if settings_owner is not None and settings_owner.poll() is None:
                settings_owner.terminate()
                try:
                    settings_owner.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    settings_owner.kill()
                    settings_owner.wait(timeout=5)
