#!/usr/bin/env python3
"""Fresh ClamAV verification must precede opening Maximum generated PDFs."""

from dataclasses import FrozenInstanceError
import importlib.util
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from maximum_sanitized_copy import SanitizedCopyOffer

sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location(
    "maximum_generated_rescan_test_gate", Path(__file__).with_name("scan-and-open.py")
)
opener = importlib.util.module_from_spec(spec)
spec.loader.exec_module(opener)


class GeneratedPDFRescanTests(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.pdf = Path(self.directory.name).resolve() / "newly sanitized.pdf"
        self.offer = SanitizedCopyOffer(b"%PDF-1.4\nfresh generated bytes", 1)
        self.pdf.write_bytes(self.offer.pdf_bytes)
        fixtures = (
            patch.object(opener, "CACHE_DB", Path(self.directory.name) / "cache.sqlite3"),
            patch.object(opener, "SCAN_REQUEST_DB",
                         Path(self.directory.name) / "requests.sqlite3"),
            patch.object(opener, "scanner_path", return_value="/installed/clamscan"),
            patch.object(opener, "check_database"),
            patch.object(opener, "intended_destination", return_value="chosen-browser"),
            patch.object(opener, "pdf_fallback_application", return_value=None),
            patch.object(opener, "verify_local_file_available"),
            patch.object(opener, "verify_launch_target"),
            patch.object(opener, "record_scan_destination"),
            patch.object(opener, "remove_quarantine"),
            patch.object(opener, "scan_engine_version", return_value="1.0"),
            patch.object(opener, "read_signature_database_version", return_value="main=42"),
        )
        for item in fixtures:
            item.start()
            self.addCleanup(item.stop)
        self.passive = patch("maximum_sanitized_copy._passive_pages", return_value=True)
        self.passive.start()
        self.addCleanup(self.passive.stop)

    @staticmethod
    def clean():
        return subprocess.CompletedProcess([], 0, "scan.pdf: OK\n", "")

    def test_fingerprint_matches_the_existing_scanner_contract(self):
        self.assertEqual(
            opener._fingerprint_generated_pdf_bytes(self.offer.pdf_bytes),
            opener.fingerprint(self.pdf),
        )

    def test_fresh_recheck_bypasses_existing_clean_content_cache(self):
        digest = opener.policy_cache_key(
            opener.fingerprint(self.pdf), True, opener.DEFAULT_SCAN_POLICY
        )
        opener.remember_clean(digest)
        self.assertTrue(opener.cached_clean(digest))

        order = []
        def scan(command, timeout):
            order.append("fresh scan")
            self.assertEqual(command[0], "/installed/clamscan")
            self.assertIn("--max-filesize=0", command)
            self.assertIn("--max-scansize=0", command)
            self.assertIn("--alert-exceeds-max=yes", command)
            self.assertIn("--alert-encrypted=yes", command)
            self.assertIn("--max-scantime=0", command)
            self.assertIn("--database=" + str(opener.DATABASE), command)
            self.assertEqual(command[-1], str(self.pdf))
            return self.clean()

        def launch(path, *, target_app=None):
            order.append("launch")
            self.assertEqual(order, ["fresh scan", "launch"])
            self.assertEqual(path, self.pdf)
            self.assertEqual(target_app, "chosen-browser")

        with patch.object(opener, "run_scan_command", side_effect=scan) as scan_command, \
                patch.object(opener, "launch_clean_file", side_effect=launch) as opened:
            result = opener.scan_and_open_generated_copy(self.pdf, self.offer)
        self.assertEqual(order, ["fresh scan", "launch"])
        scan_command.assert_called_once()
        opened.assert_called_once()
        self.assertEqual(result.status, "clean")
        self.assertFalse(result.from_cache)

    def test_generated_file_modified_before_scanning_is_never_opened(self):
        self.pdf.write_bytes(self.offer.pdf_bytes + b"\nchanged")
        with patch.object(opener, "run_scan_command") as scan, \
                patch.object(opener, "launch_clean_file") as opened:
            with self.assertRaisesRegex(RuntimeError, "differs from the sanitized copy"):
                opener.scan_and_open_generated_copy(self.pdf, self.offer)
        scan.assert_not_called()
        opened.assert_not_called()

    def test_generated_file_replaced_during_clamav_is_never_opened(self):
        def tamper(command, timeout):
            self.pdf.write_bytes(self.offer.pdf_bytes + b"\nchanged while scanning")
            return self.clean()
        with patch.object(opener, "run_scan_command", side_effect=tamper), \
                patch.object(opener, "launch_clean_file") as opened:
            with self.assertRaisesRegex(RuntimeError, "file changed"):
                opener.scan_and_open_generated_copy(self.pdf, self.offer)
        opened.assert_not_called()

    def test_malware_incomplete_and_timeout_all_block_handoff(self):
        cases = (
            subprocess.CompletedProcess([], 1, "scan.pdf: Test.Malware FOUND\n", ""),
            subprocess.CompletedProcess([], 2, "", "scan error"),
            subprocess.CompletedProcess([], 0, "scan.pdf: skipped", ""),
            subprocess.CompletedProcess([], 0, "scan.pdf: OK", "warning"),
            subprocess.TimeoutExpired(["private path"], 3),
        )
        for scan_result in cases:
            with self.subTest(case=str(scan_result)[:45]), \
                    patch.object(opener, "run_scan_command",
                                 **({"return_value": scan_result}
                                    if isinstance(scan_result, subprocess.CompletedProcess)
                                    else {"side_effect": scan_result})) as run, \
                    patch.object(opener, "launch_clean_file") as opened:
                with self.assertRaises(RuntimeError):
                    opener.scan_and_open_generated_copy(self.pdf, self.offer)
                run.assert_called_once()
                opened.assert_not_called()

    def test_fresh_signatures_required_even_with_cached_clean_verdict(self):
        digest = opener.policy_cache_key(
            opener.fingerprint(self.pdf), True, opener.DEFAULT_SCAN_POLICY
        )
        opener.remember_clean(digest)
        with patch.object(opener, "check_database",
                          side_effect=RuntimeError("Signatures are stale")), \
                patch.object(opener, "run_scan_command") as scan, \
                patch.object(opener, "launch_clean_file") as opened:
            with self.assertRaisesRegex(RuntimeError, "Signatures are stale"):
                opener.scan_and_open_generated_copy(self.pdf, self.offer)
        scan.assert_not_called()
        opened.assert_not_called()

    def test_unverified_or_forged_offers_are_not_scanned_or_opened(self):
        cases = (
            None,
            self.offer.pdf_bytes,
            SanitizedCopyOffer(b"%PDF-1.4\nother bytes", 1),
        )
        with patch("maximum_sanitized_copy._passive_pages", return_value=False), \
                patch.object(opener, "run_scan_command") as scan, \
                patch.object(opener, "launch_clean_file") as opened:
            for offer in cases:
                with self.subTest(kind=type(offer).__name__), \
                        self.assertRaises(RuntimeError):
                    opener.scan_and_open_generated_copy(self.pdf, offer)
        scan.assert_not_called()
        opened.assert_not_called()

    def test_non_pdf_output_path_is_never_scanned_or_launched(self):
        other = self.pdf.with_suffix(".txt")
        other.write_bytes(self.offer.pdf_bytes)
        with patch.object(opener, "run_scan_command") as scan, \
                patch.object(opener, "launch_clean_file") as opened:
            with self.assertRaisesRegex(RuntimeError, "saved PDF is required"):
                opener.scan_and_open_generated_copy(other, self.offer)
        scan.assert_not_called()
        opened.assert_not_called()

    def test_normal_scans_still_accept_clean_cache_and_existing_options(self):
        digest = opener.policy_cache_key(
            opener.fingerprint(self.pdf), True, opener.DEFAULT_SCAN_POLICY
        )
        opener.remember_clean(digest)
        with patch.object(opener, "run_scan_command") as scan, \
                patch.object(opener, "launch_clean_file") as opened:
            result = opener.scan_and_open(self.pdf, "/installed/clamscan")
        scan.assert_not_called()
        opened.assert_called_once()
        self.assertTrue(result.from_cache)

    def test_unavailable_native_converter_or_optional_parser_never_affects_builtin(self):
        root = Path(__file__).resolve().parent
        from protection_profiles import PROTECTION_PROFILES, ProtectionProfileID
        self.assertFalse(PROTECTION_PROFILES[ProtectionProfileID.MAXIMUM].selectable)
        scanner = (root / "scan-and-open.py").read_text(encoding="utf-8")
        self.assertIn("if requires_scan():", scanner)
        self.assertIn("if not cached_clean(cache_id):", scanner)
        with patch.object(opener, "run_scan_command", return_value=self.clean()), \
                patch.object(opener, "launch_clean_file") as opened:
            self.assertEqual(
                opener.scan_and_open(self.pdf, "/installed/clamscan").status, "clean"
            )
            opened.assert_called_once()


@unittest.skipUnless(sys.platform == "darwin",
                     "Native CoreGraphics sanitized-copy integration requires macOS")
class NativeGeneratedPDFRescanTests(unittest.TestCase):
    def test_real_rasterized_pdf_must_reenter_clamav_before_launch(self):
        from io import BytesIO
        from pypdf import PdfWriter
        from maximum_sanitized_copy import attempt_sanitized_pdf_copy

        writer = PdfWriter()
        writer.add_blank_page(width=180, height=240)
        stream = BytesIO()
        writer.write(stream)
        attempt = attempt_sanitized_pdf_copy(stream.getvalue())
        # Test-only diagnostic is a fixed enum, never raw worker output, paths,
        # source bytes, or parser messages. Production remains fail-closed.
        diagnostic = (
            attempt.failure.kind.value if attempt.failure is not None
            else "no_failure_report"
        )
        self.assertIsNotNone(attempt.offer, "safe sanitizer failure category: " + diagnostic)
        offer = attempt.offer
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "output.pdf"
            path.write_bytes(offer.pdf_bytes)
            with patch.object(opener, "CACHE_DB", Path(directory) / "cache.sqlite3"), \
                    patch.object(opener, "SCAN_REQUEST_DB",
                                 Path(directory) / "requests.sqlite3"), \
                    patch.object(opener, "scanner_path", return_value="/installed/clamscan"), \
                    patch.object(opener, "check_database"), \
                    patch.object(opener, "intended_destination",
                                 return_value="chosen-browser"), \
                    patch.object(opener, "pdf_fallback_application", return_value=None), \
                    patch.object(opener, "verify_local_file_available"), \
                    patch.object(opener, "verify_launch_target"), \
                    patch.object(opener, "record_scan_destination"), \
                    patch.object(opener, "scan_engine_version", return_value=None), \
                    patch.object(opener, "read_signature_database_version",
                                 return_value=None), \
                    patch.object(opener, "run_scan_command", return_value=subprocess.CompletedProcess(
                        [], 0, "sanitized.pdf: OK", ""
                    )) as scan, \
                    patch.object(opener, "launch_clean_file") as launched:
                result = opener.scan_and_open_generated_copy(path, offer)
                self.assertEqual(result.status, "clean")
                self.assertFalse(result.from_cache)
                scan.assert_called_once()
                launched.assert_called_once()


if __name__ == "__main__":
    unittest.main()
